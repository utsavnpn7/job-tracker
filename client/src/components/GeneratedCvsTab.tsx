import React, { useState } from 'react';
import { FileText, Download, Eye, Sparkles, RefreshCw } from 'lucide-react';

interface GeneratedCvsTabProps {
  generatedFiles: any[];
  onRefreshFiles: () => void;
  onRunAgent: (command: string) => void;
  isAgentRunning: boolean;
}

export const GeneratedCvsTab: React.FC<GeneratedCvsTabProps> = ({
  generatedFiles,
  onRefreshFiles,
  onRunAgent,
  isAgentRunning,
}) => {
  const [selectedFile, setSelectedFile] = useState<string | null>(null);

  const formatSize = (bytes: number) => {
    if (bytes < 1024) return bytes + ' B';
    if (bytes < 1024 * 1024) return (bytes / 1024).toFixed(1) + ' KB';
    return (bytes / (1024 * 1024)).toFixed(1) + ' MB';
  };

  return (
    <div>
      <div className="filter-bar" style={{ marginBottom: '1.25rem' }}>
        <div style={{ display: 'flex', alignItems: 'center', gap: '0.6rem' }}>
          <h2 style={{ fontSize: '1.25rem', fontWeight: 700 }}>Tailored CV Artifacts Hub</h2>
          <span style={{ fontSize: '0.8rem', color: 'var(--text-muted)' }}>
            `output/` directory generated by Antigravity AI agent
          </span>
        </div>

        <div style={{ display: 'flex', gap: '0.75rem' }}>
          <button className="btn-secondary" onClick={onRefreshFiles}>
            <RefreshCw size={16} /> Refresh Output Files
          </button>

          <button
            className="btn-primary"
            onClick={() => onRunAgent('pdf')}
            disabled={isAgentRunning}
          >
            <Sparkles size={16} /> Re-Generate PDF Bundle
          </button>
        </div>
      </div>

      {generatedFiles.length === 0 ? (
        <div style={{ background: 'var(--bg-card)', border: '1px solid var(--glass-border)', borderRadius: 'var(--radius-lg)', padding: '4rem 2rem', textAlign: 'center' }}>
          <FileText size={48} style={{ color: 'var(--text-muted)', marginBottom: '1rem' }} />
          <h3 style={{ fontSize: '1.1rem', fontWeight: 700, marginBottom: '0.5rem' }}>No Generated CV Artifacts Found Yet</h3>
          <p style={{ color: 'var(--text-muted)', fontSize: '0.88rem', marginBottom: '1.5rem' }}>
            Run the PDF generator or apply pipeline to produce ATS-optimized CV packages in `output/`.
          </p>
          <button className="btn-primary" style={{ margin: '0 auto' }} onClick={() => onRunAgent('pdf')}>
            Generate Default PDF CV
          </button>
        </div>
      ) : (
        <div className="cards-grid">
          {generatedFiles.map((file, idx) => {
            const isPdf = file.ext === '.pdf';
            return (
              <div key={idx} className="item-card">
                <div>
                  <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: '0.75rem' }}>
                    <span className="badge" style={{ background: isPdf ? 'rgba(244, 63, 94, 0.15)' : 'rgba(6, 182, 212, 0.15)', color: isPdf ? '#f43f5e' : '#06b6d4' }}>
                      {file.ext.toUpperCase().replace('.', '')}
                    </span>
                    <span style={{ fontSize: '0.76rem', color: 'var(--text-muted)', fontFamily: 'var(--font-mono)' }}>
                      {formatSize(file.sizeBytes)}
                    </span>
                  </div>

                  <div className="item-card-title" style={{ fontFamily: 'var(--font-mono)', fontSize: '0.92rem' }}>
                    {file.name}
                  </div>

                  <div className="item-card-sub">
                    Modified: {new Date(file.mtime).toLocaleString()}
                  </div>
                </div>

                <div style={{ display: 'flex', gap: '0.5rem', marginTop: '1rem' }}>
                  <button
                    className="btn-secondary"
                    style={{ flex: 1, padding: '0.45rem', fontSize: '0.82rem', justifyContent: 'center' }}
                    onClick={() => setSelectedFile(file.path)}
                  >
                    <Eye size={15} /> Preview
                  </button>

                  <a
                    href={file.path}
                    download={file.name}
                    className="btn-primary"
                    style={{ textDecoration: 'none', padding: '0.45rem 0.8rem', fontSize: '0.82rem', justifyContent: 'center' }}
                  >
                    <Download size={15} />
                  </a>
                </div>
              </div>
            );
          })}
        </div>
      )}

      {/* Preview Modal */}
      {selectedFile && (
        <div className="modal-overlay" onClick={() => setSelectedFile(null)}>
          <div className="modal-content" style={{ maxWidth: '900px', height: '85vh', display: 'flex', flexDirection: 'column' }} onClick={(e) => e.stopPropagation()}>
            <div className="modal-header">
              <h3 style={{ fontSize: '1.1rem', fontWeight: 700, fontFamily: 'var(--font-mono)' }}>
                Artifact Preview: {selectedFile}
              </h3>
              <button
                style={{ background: 'transparent', border: 'none', color: 'var(--text-muted)', cursor: 'pointer' }}
                onClick={() => setSelectedFile(null)}
              >
                ✕
              </button>
            </div>

            <div style={{ flex: 1, background: '#fff', borderRadius: 'var(--radius-md)', overflow: 'hidden' }}>
              <iframe
                src={selectedFile}
                title="CV Artifact Preview"
                style={{ width: '100%', height: '100%', border: 'none' }}
              />
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
